#!/usr/bin/env python3
"""cell 14, `operator credential` — jg-base im-onsite-operator-tools, root task 4.5.

Run: python3 .github/workflows/run-tests.py

What the cell must get right, and the test that pins each:

  - expiry is a FAIL and the mint date is printed: the one-year break-glass
    cannot be revoked by Omni, and expired, the sidecar reads it as absent while
    every signal stays green (`test_expired_fails`, `test_valid_prints_mint_date`);
  - the Omni `tainted-by-break-glass` label is information, never the verdict
    (`test_taint_is_information_not_verdict`: three Omni answers, one rc);
  - the one hand-off: tainted in Omni with no credential in the repo is a
    person's question — not a pass, not a fail (`test_tainted_without_credential`);
  - nothing printed is the credential, and the fixture contains it, or that
    absence proves nothing (`test_never_prints_the_credential`).

Nothing here reaches Omni or the network: `shutil.which` is replaced so
`omnictl` is never found, and the Omni half is fed from `--cluster-json`
captures. The clock is `dc._utcnow`, replaced per case, so ONE certificate
serves the valid, near-expiry and expired cases — a certificate per date would
be three fixtures that drift apart.

The certificate is generated by openssl at test time (a throwaway P-256 key,
subject O=os:operator, the way Talos encodes roles). A PEM checked into the
repo would be a second copy of the thing `repo-hygiene` scans for.
"""

from __future__ import annotations

# Keeps the SUBJECT's bytecode out of __pycache__ (jgct#96).
import sys

sys.dont_write_bytecode = True

import base64
import contextlib
import datetime
import importlib.util
import json
import pathlib
import re
import shutil
import subprocess
import tempfile
import types
import unittest
from unittest import mock

ROOT = pathlib.Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location("dc", ROOT / "scripts" / "delivery-check.py")
dc = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(dc)

_REAL_WHICH = shutil.which


def _no_omnictl(name):
    """omnictl is never found; everything else (openssl, yq) is."""
    return None if name == "omnictl" else _REAL_WHICH(name)


def _mint(tmp: pathlib.Path, org: str, days: int) -> tuple[str, str, str]:
    """(crt_b64, key_b64, notAfter YYYY-MM-DD) for a throwaway self-signed cert."""
    key, crt = tmp / f"{org}.key", tmp / f"{org}.crt"
    subprocess.run(["openssl", "req", "-x509", "-newkey", "ec", "-pkeyopt",
                    "ec_paramgen_curve:P-256", "-nodes", "-keyout", str(key),
                    "-out", str(crt), "-days", str(days), "-subj", f"/O={org}"],
                   check=True, capture_output=True)
    end = subprocess.run(["openssl", "x509", "-noout", "-enddate", "-in", str(crt)],
                         check=True, capture_output=True, text=True).stdout
    na = datetime.datetime.strptime(end.split("=", 1)[1].strip(), "%b %d %H:%M:%S %Y GMT")
    return (base64.b64encode(crt.read_bytes()).decode(),
            base64.b64encode(key.read_bytes()).decode(), na.strftime("%Y-%m-%d"))


def _talosconfig(crt_b64: str, key_b64: str) -> str:
    return ("context: bench\ncontexts:\n  bench:\n    endpoints:\n      - 10.9.1.23\n"
            f"    ca: {base64.b64encode(b'not-a-ca').decode()}\n"
            f"    crt: {crt_b64}\n    key: {key_b64}\n")


class OperatorCredentialCell(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not _REAL_WHICH("openssl"):
            raise unittest.SkipTest("openssl is not on PATH — the cell reads certificates through it")
        cls.tmp = pathlib.Path(tempfile.mkdtemp(prefix="dc-cell14-"))
        cls.op_crt, cls.op_key, cls.op_expiry = _mint(cls.tmp, "os:operator", 365)
        cls.rd_crt, cls.rd_key, _ = _mint(cls.tmp, "os:reader", 365)

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    # -- harness ------------------------------------------------------------

    def _repo(self) -> pathlib.Path:
        """A directory `_is_cluster_repo` accepts.

        What `_merged_config` returns for it is stubbed per case (it shells out
        to yq, which the test runner may not have); the file is still written so
        the cell sees a real cluster repo. `test_reads_the_real_file` covers yq.
        """
        d = pathlib.Path(tempfile.mkdtemp(prefix="repo-", dir=self.tmp))
        (d / "cluster.yaml").write_text("cluster_name: bench\n")
        return d

    def _capture(self, tainted: bool | None) -> str | None:
        """A `--cluster-json` capture file, or None for 'no capture'."""
        if tainted is None:
            return None
        labels = {dc.TAINT_LABEL: ""} if tainted else {}
        p = pathlib.Path(tempfile.mkdtemp(prefix="cap-", dir=self.tmp)) / "cluster.json"
        p.write_text(json.dumps({"metadata": {"id": "bench", "labels": labels}, "spec": {}}))
        return str(p)

    def _run(self, config: dict, *, tainted: bool | None = None,
             now: datetime.datetime | None = None):
        d = self._repo()
        args = types.SimpleNamespace(dir=str(d), cluster_json=self._capture(tainted))
        with contextlib.ExitStack() as stack:
            stack.enter_context(mock.patch.object(dc, "_merged_config", lambda root: (config, None)))
            stack.enter_context(mock.patch.object(dc.shutil, "which", _no_omnictl))
            if now is not None:
                stack.enter_context(mock.patch.object(dc, "_utcnow", lambda: now))
            return dc.cell_operator_credential(args)

    def _with_operator(self, crt=None, key=None) -> dict:
        return {"cluster_name": "bench", "provisioning_path": "omni",
                "talos_operator_config": _talosconfig(crt or self.op_crt, key or self.op_key)}

    # -- the cell is in the table ------------------------------------------

    def test_cell_is_in_the_handover_table(self):
        rows = [(n, fn) for n, _, fn in dc.HANDOVER_CELLS]
        self.assertIn((14, dc.cell_operator_credential), rows)

    # -- absent field --------------------------------------------------------

    def test_absent_field_is_the_reader_only_shape(self):
        rc, note, why = self._run({"cluster_name": "bench"})
        self.assertEqual((rc, why), (dc.PASS, None), note)
        self.assertIn("reader-only", note)
        self.assertIn("Omni not read here", note)

    def test_tainted_without_credential_is_a_persons_question(self):
        rc, note, why = self._run({"cluster_name": "bench"}, tainted=True)
        self.assertEqual((rc, why), (dc.UNKNOWN, dc.NEED_HUMAN), note)
        self.assertIn("2026-10-11", note)
        # Three histories, not two (#205): the third -- rotated and removed --
        # needs NO action, the opposite of the other two, and is the one a
        # reader would otherwise "fix" by rotating a cluster that is clean.
        self.assertIn("(c) rotated and removed", note)
        self.assertIn("(c) needs nothing", note)
        self.assertIn("rotate talos-ca", note)
        self.assertNotIn("unmeasured", note)
        # The clean label with no credential is NOT that question.
        rc, note, why = self._run({"cluster_name": "bench"}, tainted=False)
        self.assertEqual((rc, why), (dc.PASS, None), note)

    # -- present field -------------------------------------------------------

    def test_valid_prints_mint_date_and_expiry(self):
        rc, note, why = self._run(self._with_operator(), tainted=True)
        self.assertEqual((rc, why), (dc.PASS, None), note)
        today = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
        self.assertRegex(note, rf"minted {today}, expires {self.op_expiry}")
        self.assertIn("os:operator", note)
        self.assertFalse(note.startswith("EXPIRES IN"), note)

    def test_taint_is_information_not_verdict(self):
        """Three Omni answers, one rc. The notes must still differ, or the
        label was not read at all."""
        notes = {}
        for tainted in (True, False, None):
            rc, note, why = self._run(self._with_operator(), tainted=tainted)
            self.assertEqual((rc, why), (dc.PASS, None), (tainted, note))
            notes[tainted] = note
        self.assertIn(dc.TAINT_LABEL, notes[True])
        self.assertIn("unexpected", notes[False])
        self.assertIn("Omni not read here", notes[None])
        self.assertEqual(len(set(notes.values())), 3)

    def test_expired_fails(self):
        na = datetime.datetime.strptime(self.op_expiry, "%Y-%m-%d").replace(tzinfo=datetime.timezone.utc)
        rc, note, why = self._run(self._with_operator(), tainted=True,
                                  now=na + datetime.timedelta(days=2))
        self.assertEqual((rc, why), (dc.FAIL, None), note)
        self.assertIn("EXPIRED", note)
        self.assertIn(self.op_expiry, note)
        # Positive control on the clock: the same fixture two days EARLIER passes.
        rc, note, _ = self._run(self._with_operator(), tainted=True,
                                now=na - datetime.timedelta(days=2))
        self.assertEqual(rc, dc.PASS, note)

    def test_near_expiry_leads_with_it_and_still_passes(self):
        na = datetime.datetime.strptime(self.op_expiry, "%Y-%m-%d").replace(tzinfo=datetime.timezone.utc)
        rc, note, why = self._run(self._with_operator(), tainted=True,
                                  now=na - datetime.timedelta(days=10))
        self.assertEqual((rc, why), (dc.PASS, None), note)
        self.assertTrue(note.startswith("EXPIRES IN"), note)

    def test_wrong_role_fails(self):
        rc, note, why = self._run(self._with_operator(crt=self.rd_crt, key=self.rd_key), tainted=True)
        self.assertEqual((rc, why), (dc.FAIL, None), note)
        self.assertIn("os:reader", note)

    def test_garbage_value_fails_rather_than_reads_as_absent(self):
        cfg = {"cluster_name": "bench", "talos_operator_config": "pasted-by-hand"}
        rc, note, why = self._run(cfg, tainted=True)
        self.assertEqual((rc, why), (dc.FAIL, None), note)
        self.assertIn("not a talosconfig", note)

    # -- output discipline ---------------------------------------------------

    def test_never_prints_the_credential(self):
        """Every outcome, and the fixture must contain the thing being looked for."""
        cfg = self._with_operator()
        self.assertIn(self.op_crt, cfg["talos_operator_config"])
        self.assertIn(self.op_key, cfg["talos_operator_config"])
        na = datetime.datetime.strptime(self.op_expiry, "%Y-%m-%d").replace(tzinfo=datetime.timezone.utc)
        for tainted, now in ((True, None), (False, None), (None, None),
                             (True, na + datetime.timedelta(days=2))):
            _, note, _ = self._run(cfg, tainted=tainted, now=now)
            for secret in (self.op_crt, self.op_key, self.op_crt[:40], self.op_key[:40]):
                self.assertNotIn(secret, note)
            self.assertNotIn("BEGIN", note)
        _, note, _ = self._run(self._with_operator(crt=self.rd_crt, key=self.rd_key))
        self.assertNotIn(self.rd_crt[:40], note)

    # -- the real reader -----------------------------------------------------

    def test_reads_the_real_file(self):
        """Through `_merged_config` (yq), not the stub — skipped visibly without yq."""
        if not _REAL_WHICH("yq"):
            raise unittest.SkipTest("yq is not on PATH — _merged_config needs it")
        d = pathlib.Path(tempfile.mkdtemp(prefix="real-", dir=self.tmp))
        body = "cluster_name: bench\ntalos_operator_config: |\n"
        body += "".join(f"  {ln}\n" for ln in _talosconfig(self.op_crt, self.op_key).splitlines())
        (d / "cluster.yaml").write_text(body)
        args = types.SimpleNamespace(dir=str(d), cluster_json=self._capture(True))
        with mock.patch.object(dc.shutil, "which", _no_omnictl):
            rc, note, why = dc.cell_operator_credential(args)
        self.assertEqual((rc, why), (dc.PASS, None), note)
        self.assertIn(self.op_expiry, note)


if __name__ == "__main__":
    unittest.main()
